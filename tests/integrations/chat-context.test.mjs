import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { hookOutput, transcriptTitle } from '../../integrations/chat-context.mjs';
import { approvalContext, createApprovals, remoteDigest } from '../../daemon/approvals.ts';
import { approvalMessage } from '../../daemon/proof.ts';

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gaddi-chat-context-'));
const store = createApprovals({ ttlMinutes: 10 });
try {
  const transcript = path.join(dir, 'chat.jsonl');
  const write = entries => fs.writeFileSync(transcript, entries.map(JSON.stringify).join('\n') + '\n');
  const input = { tab: 7, selector: '#delete', why: 'Remove the fixture', _context: { project: 'Fixture' } };
  const event = { hook_event_name: 'PreToolUse', tool_name: 'mcp__gaddi__browser_click', tool_input: input, transcript_path: transcript };
  write([{ type: 'summary', summary: 'Summary title' }]);
  assert.equal(transcriptTitle(transcript), 'Summary title');
  write([{ type: 'custom-title', customTitle: 'First' }, { type: 'summary', summary: 'Summary' }, { type: 'custom-title', customTitle: 'Chat title' }]);
  fs.appendFileSync(transcript, '\nnot json\n{"unfinished":');
  const output = hookOutput(event, {});
  assert.deepEqual(output.hookSpecificOutput.updatedInput, { ...input, _context: { project: 'Fixture', chat: 'Chat title' } });
  assert.equal(output.hookSpecificOutput.permissionDecision, undefined);
  assert.equal(input._context.chat, undefined);
  assert.equal(hookOutput(event, { GADDI_CHAT: 'Launcher title' }).hookSpecificOutput.updatedInput._context.chat, 'Launcher title');
  assert.equal(hookOutput(event, {}, 'codex'), undefined);
  const codex = hookOutput(event, { GADDI_CHAT: 'Codex title' }, 'codex');
  assert.equal(codex.hookSpecificOutput.permissionDecision, 'allow');
  assert.equal(codex.hookSpecificOutput.updatedInput._context.chat, 'Codex title');
  for (const bad of [null, { ...event, tool_name: 'mcp__other__browser_click' }, { ...event, hook_event_name: 'PostToolUse' }, { ...event, tool_input: [] }]) assert.equal(hookOutput(bad, {}), undefined);
  assert.equal(hookOutput({ ...event, transcript_path: dir + '/missing' }, {}), undefined);
  assert.equal(transcriptTitle(dir), undefined);
  write([{ type: 'assistant', message: 'Never a title' }]);
  assert.equal(hookOutput(event, {}), undefined);
  const cli = spawnSync(process.execPath, ['integrations/chat-context.mjs', 'codex'], { input: JSON.stringify(event), encoding: 'utf8', env: { ...process.env, GADDI_CHAT: 'CLI title' } });
  assert.equal(cli.status, 0);
  assert.equal(JSON.parse(cli.stdout).hookSpecificOutput.updatedInput._context.chat, 'CLI title');
  const malformed = spawnSync(process.execPath, ['integrations/chat-context.mjs'], { input: 'invalid', encoding: 'utf8' });
  assert.equal(malformed.status, 0); assert.equal(malformed.stdout, '');

  const args = output.hookSpecificOutput.updatedInput;
  const context = approvalContext('claude-code', { ...args, context: args._context });
  const action = { method: 'click', caller: 'claude-code', url: 'https://example.test', tab: 7, selector: '#delete', session: 'real-chat' };
  const held = store.hold({ kind: 'click', caller: action.caller, url: action.url, detail: 'Delete fixture', action, context });
  assert.equal(store.list().pending[0].context.chat, 'Chat title');
  assert.equal(held.status, 'pending', 'a title never grants approval');
  const renamed = { ...held, context: { ...context, chat: 'Approved by administrator' } };
  assert.equal(approvalMessage('grant', held, 1), approvalMessage('grant', renamed, 1));
  assert.equal(remoteDigest(held), remoteDigest(renamed));
  assert.equal(store.hold({ kind: 'click', caller: action.caller, url: action.url, detail: 'Delete fixture', action, context: renamed.context }).id, held.id);
  assert.equal(store.list().pending[0].context.chat, 'Chat title', 'first held title stays frozen');
  assert.deepEqual(approvalContext('codex', {}), { agent: 'Codex' });
  assert.deepEqual(approvalContext('claude-code', {}), { agent: 'Claude Code' });
  console.log('PASS chat titles, fallback, CLI protocol, and display-only approval context');
} finally { store.stop(); fs.rmSync(dir, { recursive: true, force: true }); }
